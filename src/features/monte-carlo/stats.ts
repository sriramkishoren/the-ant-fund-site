// Small numeric helpers for the Monte Carlo engine output.
// Money formatting lives in src/lib/currency.ts so it can follow the
// user's selected currency.

export function percentile(sortedAsc: number[], p: number): number {
  if (sortedAsc.length === 0) return 0;
  if (sortedAsc.length === 1) return sortedAsc[0];
  const idx = Math.min(sortedAsc.length - 1, Math.max(0, Math.floor(p * sortedAsc.length)));
  return sortedAsc[idx];
}

